import sys
import numpy as np
from scipy.sparse import csr_matrix

print("DEMOSTRACIÓN PRÁCTICA: MATRICES DENSAS VS DISPERSAS")

# se crea una matriz de gran tamañano
# Esto simula un escenario real como la red de vuelos de OpenFlights o MovieLens
filas, columnas = 5000, 5000
matrizDensa = np.zeros((filas, columnas), dtype=float)

np.random.seed(42)
elementosNoNulos = 250000
indicesFilas = np.random.randint(0, filas, size=elementosNoNulos)
indicesCols = np.random.randint(0, columnas, size=elementosNoNulos)
valores = np.random.uniform(1.0, 100.0, size=elementosNoNulos)

matrizDensa[indicesFilas, indicesCols] = valores

# se mide el consumo de memoria de la matriz densa
bytesMatrizDensa = matrizDensa.nbytes
mbMatrizDensa = bytesMatrizDensa / (1024 * 1024)

print("REPRESENTACIÓN MATRIZ DENSA:")
print(f"Dimensiones: {filas} x {columnas} ({filas * columnas} posiciones totales)")
print(f"Elementos no nulos (NNZ): {elementosNoNulos}")
print(f"Memoria consumida: {mbMatrizDensa:.2f} MB ({bytesMatrizDensa} bytes)")

# se pivotea la matriz
pivoteMatrizDensa = csr_matrix(matrizDensa)

# se mide el consumo real de los tres arreglos internos
bytesMatrizDispersa = (
    pivoteMatrizDensa.data.nbytes +
    pivoteMatrizDensa.indices.nbytes +
    pivoteMatrizDensa.indptr.nbytes
)
memoriaMatrizDispersa = bytesMatrizDispersa / (1024 * 1024)

print(f"REPRESENTACIÓN MATRIZ DISPERSA COMPRIMIDA")
print(f"Memoria consumida (V + COL_INDEX + ROW_INDEX): {memoriaMatrizDispersa:.4f} MB ({bytesMatrizDispersa} bytes)")

# se calcula el porcentaje exacto de ahorro de memoria
ahorro_porcentaje = ((bytesMatrizDensa - bytesMatrizDispersa) / bytesMatrizDensa) * 100
print(f"RESULTADO DE EFICIENCIA:")
print(f"Ahorro total de memoria obtenido: {ahorro_porcentaje:.2f}% menos que la densa")

# prueba
vectorN = np.ones(columnas)
resultado = pivoteMatrizDensa.dot(vectorN)
print(f"OPERACIÓN MATEMÁTICA:")
print(f"Multiplicación completada ignorando ceros")
print(f"Primeros 3 resultados del vector resultante: {resultado[:3]}")